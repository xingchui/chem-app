/** 中文数字（一~九十九）转阿拉伯数字 */
function cnNum(s: string): number {
  const digits: Record<string, number> = {
    一: 1, 二: 2, 三: 3, 四: 4, 五: 5, 六: 6, 七: 7, 八: 8, 九: 9,
  }
  let total = 0
  let current = 0
  for (const ch of s) {
    if (ch === '十') {
      current = (current || 1) * 10
      total += current
      current = 0
    } else if (digits[ch]) {
      current = digits[ch]!
    }
  }
  return total + current
}

/** 章节排序键：优先解析「第X章/单元/节」或「课题N」中的序号 */
function orderKey(s: string): [number, string] {
  const ke = s.match(/^课题\s*(\d+)/)
  if (ke) return [Number(ke[1]), s]
  const m = s.match(/^第([一二三四五六七八九十]+)[章单元节]/)
  if (m) return [cnNum(m[1]!), s]
  return [9999, s]
}

function compareOrder(a: string, b: string): number {
  const [na, sa] = orderKey(a)
  const [nb, sb] = orderKey(b)
  return na - nb || sa.localeCompare(sb, 'zh')
}

/** 某教材下的章（按教材章节序号排序） */
export function getChapters(book: string): string[] {
  return [...new Set(QUESTIONS.filter(q => q.book === book).map(q => q.chapter))].sort(compareOrder)
}

/** 某章下的节（按教材课题序号排序） */
export function getSections(book: string, chapter: string): string[] {
  return [
    ...new Set(
      QUESTIONS.filter(q => q.book === book && q.chapter === chapter).map(q => q.section),
    ),
  ].sort(compareOrder)
}

/** 某节下的全部题目（按题库顺序） */
export function getSectionQuestions(book: string, chapter: string, section: string): Question[] {
  return QUESTIONS.filter(
    q => q.book === book && q.chapter === chapter && q.section === section,
  )
}
